import fs from 'node:fs';
import solc from 'solc';
const source = fs.readFileSync('contracts/GoalVault.sol','utf8');
const input = {language:'Solidity', sources:{'GoalVault.sol':{content:source}},settings:{optimizer:{enabled:true,runs:200},evmVersion:'shanghai',outputSelection:{'*':{'*':['abi','evm.bytecode.object','evm.deployedBytecode.object']}}}};
const output = JSON.parse(solc.compile(JSON.stringify(input)));
for(const e of output.errors ?? []) console.error(e.formattedMessage);
if(output.errors?.some(e=>e.severity==='error')) process.exit(1);
const c = output.contracts['GoalVault.sol'].GoalVault;
fs.mkdirSync('artifacts',{recursive:true});
fs.writeFileSync('artifacts/GoalVault.json',JSON.stringify({compiler:solc.version(),settings:input.settings,abi:c.abi,bytecode:'0x'+c.evm.bytecode.object,deployedBytecode:'0x'+c.evm.deployedBytecode.object},null,2));
fs.writeFileSync('abi.json',JSON.stringify(c.abi,null,2)+'\n');
console.log(`Compiled GoalVault using ${solc.version()}`);
